export function getDailyCard(userId: string, date: string): typeof TAROT_CARDS[0] {
  // Deterministic card based on user + date
  const seed = userId.charCodeAt(0) + userId.charCodeAt(userId.length - 1) +
    parseInt(date.replace(/-/g, '')) % 1000;
  const index = seed % TAROT_CARDS.length;
  return TAROT_CARDS[index];
}
